import { Link, useRouterState } from "@tanstack/react-router";
import {
  LayoutDashboard,
  FlaskConical,
  History,
  Package,
  BarChart3,
  Settings,
  Box,
} from "lucide-react";
import {
  Sidebar,
  SidebarContent,
  SidebarFooter,
  SidebarGroup,
  SidebarGroupContent,
  SidebarGroupLabel,
  SidebarHeader,
  SidebarMenu,
  SidebarMenuButton,
  SidebarMenuItem,
  useSidebar,
} from "@/components/ui/sidebar";
import { SimulatedBadge } from "@/components/simulated-badge";

const items = [
  { title: "Dashboard", url: "/", icon: LayoutDashboard },
  { title: "New Freshness Test", url: "/test/new", icon: FlaskConical },
  { title: "Test History", url: "/history", icon: History },
  { title: "Food Inventory", url: "/inventory", icon: Package },
  { title: "Analytics", url: "/analytics", icon: BarChart3 },
  { title: "Settings", url: "/settings", icon: Settings },
] as const;

export function AppSidebar() {
  const { state } = useSidebar();
  const collapsed = state === "collapsed";
  const path = useRouterState({ select: (r) => r.location.pathname });
  const isActive = (url: string) => (url === "/" ? path === "/" : path.startsWith(url));

  return (
    <Sidebar collapsible="icon">
      <SidebarHeader>
        <Link to="/" className="flex items-center gap-3 px-1 py-2">
          <span className="grid size-9 shrink-0 place-items-center rounded-xl bg-accent-gradient text-primary-foreground shadow-glow">
            <Box className="size-5" />
          </span>
          {!collapsed && (
            <span className="leading-tight">
              <span className="block font-display text-base font-semibold">Smart Food Box</span>
              <span className="block text-xs text-muted-foreground">Freshness lab</span>
            </span>
          )}
        </Link>
      </SidebarHeader>
      <SidebarContent>
        <SidebarGroup>
          <SidebarGroupLabel>Workspace</SidebarGroupLabel>
          <SidebarGroupContent>
            <SidebarMenu>
              {items.map((item) => (
                <SidebarMenuItem key={item.url}>
                  <SidebarMenuButton
                    asChild
                    isActive={isActive(item.url)}
                    tooltip={item.title}
                    className="h-10 rounded-xl data-[active=true]:bg-sidebar-accent data-[active=true]:text-primary"
                  >
                    <Link to={item.url}>
                      <item.icon />
                      <span>{item.title}</span>
                    </Link>
                  </SidebarMenuButton>
                </SidebarMenuItem>
              ))}
            </SidebarMenu>
          </SidebarGroupContent>
        </SidebarGroup>
      </SidebarContent>
      <SidebarFooter>
        {!collapsed && (
          <div className="glass rounded-2xl p-3 text-xs text-muted-foreground">
            <SimulatedBadge />
            <p className="mt-2">
              No ESP32 box connected. All readings are generated by the built-in simulator.
            </p>
          </div>
        )}
      </SidebarFooter>
    </Sidebar>
  );
}
